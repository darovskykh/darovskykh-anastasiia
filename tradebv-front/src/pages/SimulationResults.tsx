/** Resolve which performance band a 1-5 score falls into, from rubric meta. */
const getCurrentBand = (
  score: number,
  bands: PerformanceBandMeta[],
): PerformanceBandMeta | null =>
  bands.find((b) => score >= b.min && score <= b.max) ?? null;

/** Visual styling for a band: dot color + soft bg + readable text. */
const bandPalette = (label: string | undefined | null) => {
  const l = (label || '').toLowerCase();
  if (l.includes('advanced') || l.includes('просунутий') || l.includes('впевнений'))
    return { dot: 'bg-emerald-500', bg: 'bg-emerald-50', text: 'text-emerald-700', border: 'border-emerald-200' };
  if (l.includes('proficient') || l.includes('професійний'))
    return { dot: 'bg-green-500', bg: 'bg-green-50', text: 'text-green-700', border: 'border-green-200' };
  if (l.includes('basic') || l.includes('базовий'))
    return { dot: 'bg-amber-500', bg: 'bg-amber-50', text: 'text-amber-700', border: 'border-amber-200' };
  if (l.includes('developing') || l.includes('розвиток'))
    return { dot: 'bg-orange-500', bg: 'bg-orange-50', text: 'text-orange-700', border: 'border-orange-200' };
  return { dot: 'bg-red-500', bg: 'bg-red-50', text: 'text-red-700', border: 'border-red-200' };
};

/** Fill color for a category/indicator progress bar (1-5 score). */
const progressBarColor = (score: number): string => {
  if (score >= 4.21) return 'bg-emerald-500';
  if (score >= 3.41) return 'bg-green-500';
  if (score >= 2.41) return 'bg-amber-500';
  if (score >= 1.61) return 'bg-orange-500';
  return 'bg-red-500';
};

/** Signed raw sub-score, e.g. +3, 0, -2 (the rubric's −5..+3 scale). */
const fmtSigned = (n: number): string => (n > 0 ? `+${n}` : `${n}`);

/** Chip color for a raw sub-score (−5..+3), green positive → red negative. */
const subScoreChip = (score: number): string => {
  if (score >= 2) return 'bg-emerald-100 text-emerald-700';
  if (score >= 1) return 'bg-green-100 text-green-700';
  if (score === 0) return 'bg-slate-100 text-slate-600';
  if (score >= -2) return 'bg-orange-100 text-orange-700';
  return 'bg-red-100 text-red-700';
};

/** Windmill payload doesn't carry performance bands — we derive locally
 * from the same thresholds we used for the legacy CBD rubric. */
const getWindmillBand = (score: number): { label: string; description: string } => {
  if (score < 2.0) return { label: 'CRITICAL FAILURE', description: 'Behaviours that block a successful negotiation outcome.' };
  if (score < 3.0) return { label: 'BASIC LEVEL', description: 'Foundational behaviours present but with gaps under pressure.' };
  if (score < 3.5) return { label: 'MEETS EXPECTATIONS', description: 'Acceptable commercial baseline with room to grow.' };
  if (score < 4.3) return { label: 'CONFIDENT COMMERCIAL LEVEL', description: 'Reliable performance across most negotiation skills.' };
  return { label: 'SENIOR CBD MANAGER LEVEL', description: 'Senior-level commercial reasoning with strong impact.' };
};

